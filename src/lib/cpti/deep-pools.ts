/**
 * CPTI Deep Relationship — segmented content pools
 *
 * Why segmented:
 *   The original PRACTICE_POOL (36 items, 30 picked) felt generic because
 *   long-distance, married, and dating couples all received the same
 *   "每周固定 30 分钟无议程晚饭" advice. That broke the paid promise
 *   ("拿来即用").
 *
 * Design rules:
 *   - 6 relationship stages, each with ≥40 stage-specific practices.
 *   - All practices are *actions a couple can do this week* — not abstract
 *     advice ("communicate more").
 *   - Landmines pool ≥ 60, drawn from real failure modes across stages.
 *   - All pools must be deterministically pickable via pickN(slug, n).
 */

