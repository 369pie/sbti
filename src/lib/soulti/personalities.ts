export function getSoultiRarity(slug: string): SoultiRarityInfo {
  const entry = SOULTI_SLUG_RARITY[slug] ?? { tier: 'common' as SoultiRarityTier, pct: 5.0 };
  const config = SOULTI_RARITY_CONFIG[entry.tier];
  return { tier: entry.tier, populationPct: entry.pct, ...config };
}

