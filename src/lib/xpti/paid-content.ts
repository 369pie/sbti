export function getDialogueScriptsForPairing(
  pairingId: TensionPairingId,
): DialogueScript[] {
  const ids = DIALOGUE_BY_PAIRING[pairingId] ?? [];
  const map = new Map(DIALOGUE_SCRIPTS.map((s) => [s.id, s]));
  const out: DialogueScript[] = [];
  for (const id of ids) {
    const s = map.get(id);
    if (s) out.push(s);
  }
  return out;
}

