export interface LoveLetter {
  openingLine: string;
  bodyParagraphs: string[];
  closingLine: string;
}

const LETTER_OPENERS: Record<TensionPairingId, string> = {
  mirror: '写给我的另一个自己——',
  magnet: '写给带我上路又替我收尾的人——',
  tide: '写给和我涨落同频的人——',
  fugue: '写给我的另一个声部——',
  orbit: '写给我绕行的中心——',
  spark: '写给那道烧穿我的光——',
};

const LETTER_CLOSERS: Record<TensionPairingId, string> = {
  mirror: '当我看不清自己时，我会看向你。',
  magnet: '我把方向盘留给你，不是让步，是信任。',
  tide: '我不怕潮退，因为我知道你会再涨上来。',
  fugue: '我们不同步，但我们从未真正错过。',
  orbit: '我愿意一直绕着你，但也请允许我偶尔转向。',
  spark: '别怕烧痛——我在这里，不走。',
};

function joinParts(parts: string[]): string {
  return parts.filter(Boolean).join('');
}

export function composeLoveLetter(input: {
  pairingId: TensionPairingId;
  fromNickname: string | null;
  toNickname: string | null;
  signatureFrom: string;
  signatureTo: string;
}): LoveLetter {
  const { pairingId, fromNickname, toNickname, signatureFrom, signatureTo } = input;
  const to = toNickname ?? '你';
  const from = fromNickname ?? '我';
  return {
    openingLine: `${to}——${LETTER_OPENERS[pairingId]}`,
    bodyParagraphs: [
      joinParts([
        `我注意到你${signatureTo}——`,
        '这也是我第一次，认真想要记住一个人的节奏。',
      ]),
      joinParts([
        `而我，${signatureFrom}——`,
        '我知道我们之间不是一场对仗，是一种默契地配合。',
      ]),
      '我希望我们能：吵得更轻，沉默得更稳，在彼此不在场时仍然是一对。',
    ],
    closingLine: `${LETTER_CLOSERS[pairingId]}  ——${from}`,
  };
}
