/** 按 slug 查找 WTFTI 人格 */
export function getWtftiPersonality(slug: string): WtftiPersonality | undefined {
  return WTFTI_PERSONALITIES.find(p => p.slug === slug);
}

/** 获取所有 WTFTI slug */
export function getWtftiSlugs(): string[] {
  return WTFTI_PERSONALITIES.map(p => p.slug);
}

/** 按编号查找 */
export function getWtftiByNumber(number: string): WtftiPersonality | undefined {
  return WTFTI_PERSONALITIES.find(p => p.number === number);
}

