/**
 * 选句逻辑：
 * 1. 抽 3 张牌（每张是 0-N 的人格 idx）映射到 3 个 stance
 * 2. 多数票决定卡片基调 stance
 * 3. 用 seed 在该 stance 池里取一句（确定性）
 *
 * stance 映射规则（与人格 W/T/F 倾向粗对齐，但只用 idx 简化）：
 *   idx % 3 === 0 → go
 *   idx % 3 === 1 → wait
 *   idx % 3 === 2 → flow
 */
export function pickStanceFromDraw(picks: number[]): DecisionStance {
  const tally: Record<DecisionStance, number> = { go: 0, wait: 0, flow: 0 };
  picks.forEach((p) => {
    const m = ((p % 3) + 3) % 3;
    if (m === 0) tally.go += 1;
    else if (m === 1) tally.wait += 1;
    else tally.flow += 1;
  });
  // 平票优先 flow（最温和），其次 wait，最后 go
  const order: DecisionStance[] = ['go', 'wait', 'flow'];
  return order.reduce((best, s) => (tally[s] > tally[best] ? s : best), 'flow' as DecisionStance);
}

/**
 * 给定场景 + stance + seed，确定性返回一句金句。seed 越大越深入池子尾部。
 *
 * `premium=true` 时偏向"高级池"——也就是池子的后半段（更长、更隐喻、更冷门）。
 * decision-pack 解锁后传 true，对应 SKU 描述里的「高级金句池」。
 */
export function pickQuote(
  scenarioId: DecisionScenarioId,
  stance: DecisionStance,
  seed: number,
  premium = false,
): QuoteEntry {
  const pool = QUOTES[scenarioId][stance];
  const safeSeed = Math.abs(Math.floor(seed)) || 0;
  if (!premium || pool.length < 4) {
    return pool[safeSeed % pool.length];
  }
  const offset = Math.floor(pool.length / 2);
  const premiumLen = pool.length - offset;
  return pool[offset + (safeSeed % premiumLen)];
}

