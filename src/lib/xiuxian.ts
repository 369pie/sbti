/** 获取全部修仙皮肤数据 */
export function getAllXiuxianSkins(): XiuxianSkin[] {
  const launchOnlySkins = getXiuxianLaunchOnlyTypes()
    .map((type) => getXiuxianV2Skin(type.slug))
    .filter((skin): skin is XiuxianSkin => Boolean(skin));

  return [...XIUXIAN_DATA.map((skin) => getXiuxianSkin(skin.slug) ?? skin), ...launchOnlySkins];
}

