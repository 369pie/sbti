export function getFlowerRarity(slug: string): FlowerRarityInfo {
  const entry = FLOWER_SLUG_RARITY[slug] ?? { tier: 'common' as FlowerRarityTier, pct: 5.0 };
  const config = FLOWER_RARITY_CONFIG[entry.tier];
  return { tier: entry.tier, populationPct: entry.pct, ...config };
}

