// ─── 构建 29 条 personalities ─────────────────────────────────
function buildPersonalities(): HogtiPersonality[] {
  return MAP.map(([slug, number, characterId]) => {
    const copy = COPY[slug];
    if (!copy) {
      // Fallback — 任何 slug 缺失映射时的默认值
      return {
        slug,
        number,
        characterId,
        tagline: '还在写霍格沃茨录取通知…',
        tags: ['⚡ 待定', '🧙 待定', '📜 待定'],
        emoji: '⚡',
        copy: {
          wtfHit: '你的霍格沃茨人格正在赶来。',
          osTranslation: '',
          symptoms: [],
          closer: '',
        },
      };
    }
    return { slug, number, characterId, ...copy };
  });
}

export const HOGTI_PERSONALITIES: HogtiPersonality[] = buildPersonalities();

export function getHogtiPersonality(slug: string): HogtiPersonality | undefined {
  return HOGTI_PERSONALITIES.find(p => p.slug === slug);
}

export function getHogtiSlugs(): string[] {
  return HOGTI_PERSONALITIES.map(p => p.slug);
}

/** House accent color for a slug (used by gallery-data) */
export function getHogtiItemColor(slug: string): string {
  const p = getHogtiPersonality(slug);
  if (!p) return '#3a2f6b';
  const char = HOG_CHARACTERS.find(c => c.id === p.characterId);
  if (!char) return '#3a2f6b';
  return HOG_HOUSES[char.house]?.accent ?? '#3a2f6b';
}

/** House emoji for a slug (used by gallery-data) */
export function getHogtiItemEmoji(slug: string): string {
  const p = getHogtiPersonality(slug);
  if (!p) return '⚡';
  const char = HOG_CHARACTERS.find(c => c.id === p.characterId);
  if (!char) return '⚡';
  return HOG_HOUSES[char.house]?.emoji ?? '⚡';
}

/** Character name (full display name) for a slug */
export function getHogtiCharacterName(slug: string): string {
  const p = getHogtiPersonality(slug);
  if (!p) return slug;
  const char = HOG_CHARACTERS.find(c => c.id === p.characterId);
  return char?.name ?? slug;
}

/** 取当前 slug 对应的 HP 角色全量信息 */
export function getHogtiCharacter(slug: string): HogCharacter | undefined {
  const p = getHogtiPersonality(slug);
  if (!p) return undefined;
  return getHogCharacter(p.characterId);
}

