export function getFengPersonality(slug: string): FengPersonality | undefined {
  return FENG_PERSONALITIES.find(p => p.slug === slug);
}

export function getFengSlugs(): string[] {
  return FENG_PERSONALITIES.map(p => p.slug);
}

export function getFengTypeImage(slug: string): string {
  const p = getFengPersonality(slug);
  const emoji = p ? p.emoji : '💀';
  const color = p ? p.color : '#39ff14';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="400" viewBox="0 0 400 400">
    <rect width="400" height="400" fill="#0a0a0a"/>
    <rect x="20" y="20" width="360" height="360" rx="40" fill="none" stroke="${color}" stroke-width="4"/>
    <text x="200" y="220" font-size="160" text-anchor="middle" dominant-baseline="middle">${emoji}</text>
  </svg>`;
  return `data:image/svg+xml;base64,${typeof Buffer !== 'undefined' ? Buffer.from(svg).toString('base64') : btoa(svg)}`;
}
