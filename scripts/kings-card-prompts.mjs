export function buildKingsCardPrompt({ name, code, heroRef, tagline, visualConcept, symptoms, quote, accentColor }) {
  const safeSymptoms = symptoms || [];

  return [
    '[Overall Style & Card Structure]',
    'A premium gaming personality atlas card, vertical 3:4 format.',
    'Art style: NEW CHINESE STYLE (新中式国潮) illustration with bold cel-shaded anime coloring.',
    '融合传统中国水墨笔触与现代游戏热血感，配色高饱和、高对比。',
    '角色要有「被说中了」的梗图气质——夸张、狼狈、自嘲、有槽点，而不是正经帅气。',
    '像小红书爆款截图卡，一眼看懂这个人在峡谷是什么德行。',
    'CRITICAL: 2D illustration only. No photorealism, no 3D render, no realistic human proportions.',
    `Primary accent color: ${accentColor}.`,
    '',
    '[Top Typography Zone]',
    `At the very top, small text reading "王者TI · 峡谷人格图鉴".`,
    `Below it, large bold Chinese title text reading "${name}".`,
    `Below the title, stylized code text reading "${code}" and smaller text "(${heroRef})".`,
    `Below that, a short tagline reading "你总是……${tagline}".`,
    'All Chinese text must be highly readable, accurate, no garbling.',
    '',
    '[Center Illustration Zone]',
    `Main illustration: a single character scene showing "${visualConcept}"`,
    'The character must feel like a recognizable gaming archetype — exaggerated, meme-able, relatable.',
    'Keep the character behind the text layer if overlapping.',
    '',
    '[Bottom Information Zone]',
    'Near the lower part of the card, place three rounded tag cards in one row.',
    `Tag 1: "${safeSymptoms[0] || ''}"`,
    `Tag 2: "${safeSymptoms[1] || ''}"`,
    `Tag 3: "${safeSymptoms[2] || ''}"`,
    `At the absolute bottom, add a dark rounded banner with contrasting text reading: "${quote}"`,
    'Do not show label prefixes. Render the actual text directly.',
    '',
    'negative prompt: garbled text, misspelled Chinese, unreadable, photorealistic, heavy 3D render,',
    'low poly, papercraft, horror, gore, NSFW, busy background, watermark, logo, extra characters,',
    'matte surface, fabric texture, clay, knitted',
  ].join('\n\n');
}

